'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { existsSync, readFileSync } = require('node:fs');
const { join } = require('node:path');

const root = join(__dirname, '..');
const config = JSON.parse(readFileSync(join(root, 'app.json'), 'utf8')).expo;
const app = readFileSync(join(root, 'App.js'), 'utf8');
const home = readFileSync(join(root, 'src', 'UltraHome.js'), 'utf8');
const deposit = readFileSync(join(root, 'src', 'DepositScreen.js'), 'utf8');
const manifest = readFileSync(join(root, 'android', 'app', 'src', 'main', 'AndroidManifest.xml'), 'utf8');

test('Crowned Rupee logo is integrated into launcher, splash, login, navigation, dashboard and Add Money', () => {
  const logo = './assets/paisapay-crowned-rupee-logo.png';
  assert.equal(config.icon, logo);
  assert.equal(config.version, '1.1.29');
  assert.equal(config.android.versionCode, 40);
  assert.equal(config.android.adaptiveIcon.backgroundColor, '#050505');
  assert.equal(config.splash.backgroundColor, '#050505');
  const androidGradle = readFileSync(join(root, 'android', 'app', 'build.gradle'), 'utf8');
  assert.match(androidGradle, /versionCode 40/);
  assert.match(androidGradle, /versionName "1\.1\.29"/);
  assert.equal(config.android.adaptiveIcon.foregroundImage, logo);
  assert.equal(config.splash.image, logo);
  assert.ok(existsSync(join(root, config.icon)));
  assert.ok(existsSync(join(root, config.splash.image)));
  assert.equal((app.match(/require\('\.\/assets\/paisapay-crowned-rupee-mark\.png'\)/g) || []).length, 3);
  assert.ok(existsSync(join(root, 'assets', 'paisapay-crowned-rupee-mark.png')));
  assert.match(app, /width: 132, height: 132/);
  assert.match(app, /width: 104, height: 104/);
  assert.match(app, /width: 42, height: 42/);
  assert.match(app, /blue: '#986500'/);
  assert.match(app, /gold: '#B88112'/);
  assert.match(app, /bg: '#FFFDF7'/);
  assert.doesNotMatch(app, /paisapay-purple-eagle-logo\.png/);
  assert.match(home, /\.\.\/assets\/paisapay-crowned-rupee-mark\.png/);
  assert.match(home, /height: 48, width: 48/);
  assert.doesNotMatch(home, /Some money actions are unavailable/);
  assert.match(deposit, /\.\.\/assets\/paisapay-deposit-promo\.png/);
  assert.match(deposit, /source=\{depositPromoBanner\}/);
  assert.match(deposit, /backgroundColor: '#050505'/);
  assert.match(deposit, /heroImageWrap: \{ height: 178, width: '100%'/);
  assert.match(deposit, /ARTWORK ONLY · REWARDS ARE NOT GUARANTEED/);
  assert.match(deposit, /resizeMode="cover"/);
  assert.doesNotMatch(deposit, /disabledHeroImageWrap|inactivePromoImage|depositPromoStatusTag/);
  assert.doesNotMatch(deposit, /QUICK MATCHING UNAVAILABLE/);
  assert.match(deposit, /blurRadius=\{0\}/);
  assert.match(home, /backgroundColor: '#FFFFFF'/);
  assert.doesNotMatch(home, /apiGet\('\/api\/v1\/withdrawals'\)/);
  assert.match(app, /KeyboardAvoidingView/);
  assert.match(app, /keyboardAware: true/);
  assert.match(app, /runInBackground\)\(loadPrivateData/);
  assert.notEqual(config.icon, '../apps/admin-app/assets/paisapay-admin-emblem.png');
  assert.doesNotMatch(app, /paisapay-customer-(?:emblem|brand)\.png/);
  assert.ok(config.android.blockedPermissions.includes('android.permission.SYSTEM_ALERT_WINDOW'));
  assert.ok(config.android.blockedPermissions.includes('android.permission.RECORD_AUDIO'));
  assert.match(manifest, /android\.permission\.SYSTEM_ALERT_WINDOW" tools:node="remove"/);
  assert.match(manifest, /android\.permission\.RECORD_AUDIO" tools:node="remove"/);
  assert.match(manifest, /android\.permission\.WRITE_EXTERNAL_STORAGE" tools:node="remove"/);
  assert.match(manifest, /android\.permission\.READ_EXTERNAL_STORAGE/);
});
